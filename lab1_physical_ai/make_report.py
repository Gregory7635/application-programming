def _fmt(par, align=WD_ALIGN_PARAGRAPH.JUSTIFY, indent=True, after=6, before=0, spacing=1.15):
    pf = par.paragraph_format
    par.alignment = align
    pf.first_line_indent = Cm(1.25) if indent else None
    pf.line_spacing = spacing
    pf.space_after = Pt(after)
    pf.space_before = Pt(before)
    return par


def p(text, bold=False, lead=None):
    """Абзац основного текста: по ширине, отступ 1,25 см, интервал 1,15. lead - жирное начало."""
    par = _fmt(doc.add_paragraph())
    if lead:
        par.add_run(lead + " ").bold = True
    par.add_run(text).bold = bold
    return par


def heading(text):
    par = _fmt(doc.add_paragraph(), align=None, indent=False, before=12)
    par.paragraph_format.keep_with_next = True
    par.add_run(text).bold = True
    return par


def bullets(items):
    for it in items:
        p("– " + it)


_fig_no = 0


def figure(name, caption, width=None):
    global _fig_no
    _fig_no += 1
    caption = re.sub(r"^Рис\. \d+\.\s*", "", caption)
    _fmt(doc.add_paragraph(), align=WD_ALIGN_PARAGRAPH.CENTER, indent=False).add_run().add_picture(
        str(FIG / name), width=Cm(width) if width else TEXT_WIDTH)
    _fmt(doc.add_paragraph(f"Рисунок {_fig_no} – {caption}"), align=WD_ALIGN_PARAGRAPH.CENTER,
         indent=False, after=10)


def table(header, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(header))
    # рамка как в образце: одинарные линии 0,5 pt
    borders = OxmlElement("w:tblBorders")
    for side in ("top", "left", "bottom", "right", "insideH", "insideV"):
        b = OxmlElement(f"w:{side}")
        for k, v in (("val", "single"), ("sz", "4"), ("space", "0"), ("color", "auto")):
            b.set(qn(f"w:{k}"), v)
        borders.append(b)
    t._tbl.tblPr.append(borders)
    for i, h in enumerate(header):
        t.rows[0].cells[i].paragraphs[0].add_run(h).bold = True
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].paragraphs[0].add_run(str(v))
    for row in t.rows:
        for i, cell in enumerate(row.cells):
            if widths:
                cell.width = Cm(widths[i])
            for par in cell.paragraphs:
                par.paragraph_format.space_after = Pt(0)
                for run in par.runs:
                    run.font.size = Pt(12)
    _fmt(doc.add_paragraph(), after=0)
    return t

